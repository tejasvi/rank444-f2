#!/bin/bash
# mk_batch.sh OUT NAME "IMPORTS" "CLASSES": a Lean module that collects the run theorems of the
# classes in CLASSES (space-separated; theorem B334.E1x.R<c>.run_<c> for each) into Tab2.RunsFor [c1, ..., ck] with
# a runs_cons chain (Tab2/Dispatch.lean). IMPORTS: space-separated module names that define those theorems.
# Refuses to overwrite OUT.
OUT=${1:?out}; NAME=${2:?name}; IMPS=${3:?imports}; CLS=${4:?classes}
[ -e "$OUT" ] && { echo "exists: $OUT"; exit 1; }
{
  for m in $IMPS; do echo "import $m"; done
  echo "import B334.Tab2.Dispatch"
  echo ""
  echo "/-! # The run theorems of the batch \`$NAME\` as one \`Tab2.RunsFor\` fact (generated by"
  echo "a script) -/"
  echo ""
  echo "namespace B334.E1x.$NAME"
  echo "open B334.Tab2"
  echo ""
  printf 'theorem runs : RunsFor [%s] :=\n' "$(echo $CLS | sed 's/ /, /g')"
  n=0; for c in $CLS; do n=$((n+1)); done
  line="  "; for c in $CLS; do line="${line}runs_cons R$c.run_$c ("; done
  line="${line}runs_nil"; for c in $CLS; do line="${line})"; done
  echo "$line"
  echo ""
  echo "end B334.E1x.$NAME"
} > "$OUT"
echo "wrote $OUT ($n classes)"
