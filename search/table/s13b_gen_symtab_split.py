#!/usr/bin/env python3
"""s13b_gen_symtab_split.py SYMTAB_LEAN OUT_DIR [PARTS] : the range split of the kernel facts of the witness tables.

Memory hygiene for the release rule (every module < 8 GB decimal under -M 7600): the unsplit facts `wc_fact_o` (modules
SymTabWC_<o>, 12.7-13.0 GB) and `wb_fact` (SymTabOrb, 11.7 GB) evaluate all 4096 entries of a table in one kernel
check.  This script writes, under OUT_DIR (a fresh directory; files are installed into B334/Tables of the Lean tree):
  Split/WC_<o>_<j>.lean  part j of wc_fact_o:  allFrom (C * j) C (wcAt o WC_o CORB_o) = true, by decide +kernel;
  Split/WB_<j>.lean      part j of wb_fact:    allFrom (C * j) C wbOK = true, by decide +kernel;
  SymTabWC_<o>.lean      wc_fact_o : wcOK o WC_o CORB_o = true, from its parts (allLT_of_parts);
  SymTabOrb.lean         orbm_fact (as before, by decide +kernel) and wb_fact : allLT 4096 wbOK = true, from its parts;
with C = 4096 / PARTS (default PARTS = 8).  The theorem names and statements of SymTabWC_<o> and SymTabOrb are those of
s13_gen_symtab.py, so SymTabWC, SymFacts and their users are unchanged.  allFrom, allLT_of_parts, wcAt and wcOK_eq are in
the hand-written B334/Tables/Split/Range.lean.  The orbit minima are read from SYMTAB_LEAN (def ORBL), and the
definitions the parts rely on are checked to be present there.  The script only renders text: the kernel checks every
part, and the combining proofs check that the parts cover 0 … 4095.
"""
import hashlib
import os
import re
import sys

N = 4096
GEN = 'a script'
HDR = ['set_option maxRecDepth 1000000', 'set_option maxHeartbeats 0', '']


def main():
    symtab, out = sys.argv[1], sys.argv[2]
    P = int(sys.argv[3]) if len(sys.argv) > 3 else 8
    assert P >= 1 and N % P == 0, 'PARTS must divide 4096'
    C = N // P
    src = open(symtab).read()
    m = re.search(r'^def ORBL : List Nat := \[([0-9, ]+)\]$', src, re.M)
    assert m, 'no ORBL in %s' % symtab
    orbl = [int(x) for x in m.group(1).split(',')]
    assert len(orbl) == 15 and len(set(orbl)) == 15, orbl
    for o in orbl:
        assert re.search(r'^def WC_%d : Nat := 0x[0-9a-f]+$' % o, src, re.M), o
        assert re.search(r'^def CORB_%d : Nat := 0x[0-9a-f]+$' % o, src, re.M), o
    assert re.search(r'^def wcOK \(o W C : Nat\) : Bool := allLT 4096 \(fun c => c == 0 \|\|$', src, re.M)
    assert re.search(r'^def wbOK \(b : Nat\) : Bool := ', src, re.M)
    os.makedirs(os.path.join(out, 'Split'))
    sha = {}

    def put(rel, lines):
        path = os.path.join(out, rel)
        with open(path, 'x') as fh:
            fh.write('\n'.join(lines) + '\n')
        with open(path, 'rb') as fh:
            sha[rel] = hashlib.sha256(fh.read()).hexdigest()

    def combine(fact, stmt, fn, partname, nparts):
        return [
            'theorem %s : %s := by' % (fact, stmt),
        ] + (['  rw [wcOK_eq]'] if fact.startswith('wc_fact') else []) + [
            '  exact allLT_of_parts %d (%s) %d (fun j hj => by' % (C, fn, nparts),
            '    interval_cases j',
            '    exacts [%s])' % ', '.join('%s%d' % (partname, j) for j in range(nparts)),
        ]

    for o in orbl:
        for j in range(P):
            put('Split/WC_%d_%d.lean' % (o, j), ['import B334.Tables.Split.Range', ''] + HDR + [
                '/-! # `WC` kernel fact for the orbit minimum %d, part %d of %d (masks %d … %d). GENERATED by %s;'
                % (o, j, P, C * j, C * j + C - 1, GEN),
                'do not edit. -/', '',
                'namespace B334.Tab', 'open B334.Core', '',
                'theorem wc_part_%d_%d : allFrom (%d * %d) %d (wcAt %d WC_%d CORB_%d) = true := by decide +kernel'
                % (o, j, C, j, C, o, o, o), '',
                'end B334.Tab'])
        put('SymTabWC_%d.lean' % o, ['import B334.Tables.Split.WC_%d_%d' % (o, j) for j in range(P)] + [
            '',
            '/-! # `WC` kernel fact for the orbit minimum %d, from its %d range parts `Split/WC_%d_<j>`. GENERATED by'
            % (o, P, o),
            '%s; do not edit. -/' % GEN, '',
            'namespace B334.Tab', 'open B334.Core', ''] +
            combine('wc_fact_%d' % o, 'wcOK %d WC_%d CORB_%d = true' % (o, o, o), 'wcAt %d WC_%d CORB_%d' % (o, o, o),
                    'wc_part_%d_' % o, P) + ['', 'end B334.Tab'])
    for j in range(P):
        put('Split/WB_%d.lean' % j, ['import B334.Tables.Split.Range', ''] + HDR + [
            '/-! # Kernel fact for the witness table `WB`, part %d of %d (masks %d … %d). GENERATED by'
            % (j, P, C * j, C * j + C - 1),
            '%s; do not edit. -/' % GEN, '',
            'namespace B334.Tab', 'open B334.Core', '',
            'theorem wb_part_%d : allFrom (%d * %d) %d wbOK = true := by decide +kernel' % (j, C, j, C), '',
            'end B334.Tab'])
    put('SymTabOrb.lean', ['import B334.Tables.Split.WB_%d' % j for j in range(P)] + [''] + HDR + [
        '/-! # Kernel facts: `ORBM` = `ORBL`, and the witness table `WB` (from its %d range parts' % P,
        '`Split/WB_<j>`). GENERATED by %s; do not edit. -/' % GEN, '',
        'namespace B334.Tab', 'open B334.Core', '',
        '/-- `ORBM` has exactly the bits `ORBL` -/',
        'theorem orbm_fact : allLT 4096 (fun v => ORBM.testBit v == ORBL.contains v) = true := by decide +kernel',
        '/-- every nonzero `b` has a listed `(S, S⁻¹)`, `S S⁻¹ = I`, with `b S ∈ ORBM` -/'] +
        combine('wb_fact', 'allLT 4096 wbOK = true', 'wbOK', 'wb_part_', P) + ['', 'end B334.Tab'])
    for rel in sorted(sha):
        print(sha[rel][:16], rel)
    print('s13b: %d files, PARTS=%d, C=%d, orbit minima %s' % (len(sha), P, C, orbl))


if __name__ == '__main__':
    main()
