#!/usr/bin/env python3
"""s22_tab2lean.py TABLE_V2_TSV OUT_DIR [MONO_WIT_TSV] : the class table of the result as Lean data (B334/Tab2), from
table_v2.tsv (and mono_wit.tsv, the witnesses for the monotone Route B classes, written by s23_monowit.py).

Writes, under OUT_DIR (= .../B334/Tab2):
  Data.lean     `basisOf c : List Nat` and `lbOf c : Nat` for c < 710 (lbOf = the lb the point IPs use, 0 for a class
                they do not use), as balanced comparison trees (about 10 comparisons per lookup in the kernel), and
                `routeOf c`;
  DegData.lean  `degRows`: one entry (c, e, l, s, j, subs) per class whose route is `deg` (L5b): the extra vector e,
                Wang's witness l (query & 0xffff) and s (store), acting as v -> l v s^-1 = actF l (invN s) v, the target
                class j, and for every generator x of basis(c) ++ [e] the subset of basis(j) whose XOR is the image.
                With MONO_WIT_TSV, also one entry per monotone class (table route `routeB` with rb_mono = yes: no IP of
                its own, its bound is that of a superspace class j): e = 0 and the witness (l, s, j); the class then has
                route 1 (the same lemma, L5a through a G0 element), not an E1 route.
Self-checks before writing: every image lies in span(basis(j)) (the subset found), l and s invertible, lb(c) <= lb(j),
route consistency, dim j > dim c for the monotone entries, and the subsets found equal the sub<i> columns of MONO_WIT_TSV.
Stdlib only; light.
"""
import os
import sys


def mulF(u, v):
    """the 9-bit matrix product of B334.E1x.mulF (entry (i, j) at bit 3i+j)"""
    r = 0
    for i in range(3):
        for j in range(3):
            b = 0
            for k in range(3):
                b ^= ((u >> (3 * i + k)) & 1) & ((v >> (3 * k + j)) & 1)
            r |= b << (3 * i + j)
    return r


I3 = 273
INV = {}
for m in range(512):
    for n in range(512):
        if mulF(m, n) == I3:
            INV[m] = n
            break


def actF(p, q, v):
    return mulF(mulF(p, v), q)


def xor_subset(B, y):
    for s in range(1 << len(B)):
        v = 0
        for i, b in enumerate(B):
            if (s >> i) & 1:
                v ^= b
        if v == y:
            return s
    return None


def tree(name, ty, vals, lo, hi, ind):
    """a balanced comparison tree over c in [lo, hi)"""
    if hi - lo == 1:
        return vals[lo]
    mid = (lo + hi) // 2
    return 'if c < %d then %s else %s' % (mid, '(' + tree(name, ty, vals, lo, mid, ind) + ')',
                                          '(' + tree(name, ty, vals, mid, hi, ind) + ')')


def main():
    src, out = sys.argv[1], sys.argv[2]
    mono = {}
    if len(sys.argv) > 3:
        mh = None
        for ln in open(sys.argv[3]):
            f = ln.rstrip('\n').split('\t')
            if mh is None:
                mh = f
                continue
            d = dict(zip(mh, f))
            subs_f = [int(d['sub%d' % i]) for i in range(4) if d['sub%d' % i] not in ('', '-')]
            mono[int(d['c'])] = (int(d['j']), int(d['l']), int(d['s']), subs_f)
    rows = {}
    hdr = None
    for ln in open(src):
        f = ln.rstrip('\n').split('\t')
        if hdr is None:
            hdr = f
            continue
        d = dict(zip(hdr, f))
        rows[int(d['c'])] = d
    N = max(rows) + 1
    assert sorted(rows) == list(range(N)), 'classes must be 0..N-1'
    basis = {c: ([int(x) for x in rows[c]['basis'].split(',')] if rows[c]['basis'] not in ('', '-') else []) for c in rows}
    lb = {}
    for c in rows:
        v = rows[c]['lb_used']
        lb[c] = int(v) if v not in ('', '-') else 0
    # Data.lean
    blist = ['[%s]' % ', '.join(str(x) for x in basis[c]) for c in range(N)]
    llist = [str(lb[c]) for c in range(N)]
    rcode = {'flat': 0, 'methodK': 0, 'lcc': 0, 'deg': 1, 'routeB': 2, 'lift': 2, 'raised': 2, 'point': 3, 'MISSING': 3}
    rlist = []
    for c in range(N):
        r = rcode[rows[c]['route']]
        if c in mono:
            assert rows[c]['route'] == 'routeB' and rows[c]['rb_mono'] == 'yes', ('monotone witness for a non-monotone class', c)
            r = 1
        assert r < 3 or lb[c] == 0, ('class with an IP bound but no route', c)
        rlist.append(str(r))
    nmono_tab = sum(1 for c in rows if rows[c]['route'] == 'routeB' and rows[c]['rb_mono'] == 'yes')
    D = ['/-! # The class table of the result (GENERATED by a script;',
         'do not edit). `basisOf c`: the basis of class `c`; `lbOf c`: the bound the two point IPs use',
         'for it (0 for the 8 classes they do not use). Balanced comparison trees, about 10 comparisons per lookup. -/', '',
         'namespace B334.Tab2', '',
         'def basisOf (c : Nat) : List Nat :=', '  ' + tree('basisOf', 'List Nat', blist, 0, N, 2), '',
         'def lbOf (c : Nat) : Nat :=', '  ' + tree('lbOf', 'Nat', llist, 0, N, 2), '',
         '/-- the route of class `c`: 0 = direct (flattening, method K, row 44), 1 = degenerate or monotone (L5b, an entry',
         'of `degRows`), 2 = an E1 run (Route B, lifted, raised), 3 = no route (then `lbOf c = 0`: the point IPs do not',
         'use the class) -/',
         'def routeOf (c : Nat) : Nat :=', '  ' + tree('routeOf', 'Nat', rlist, 0, N, 2), '',
         '/-- the number of classes -/', 'def nCls : Nat := %d' % N, '', 'end B334.Tab2']
    open(os.path.join(out, 'Data.lean'), 'w').write('\n'.join(D) + '\n')
    # DegData.lean
    ents = []
    nbad = 0
    nmono = 0
    for c in range(N):
        d = rows[c]
        if c in mono:
            j, l, s, subs_f = mono[c]
            e = 0
            assert l in INV and s in INV, ('monotone witness', c)
            if not len(basis[c]) < len(basis[j]):
                nbad += 1
                print('MONOTONE DIM: class %d dim %d, target %d dim %d' % (c, len(basis[c]), j, len(basis[j])))
            nmono += 1
        elif d['route'] == 'deg':
            e, q, s, j = int(d['deg_e']), int(d['deg_q']), int(d['deg_s']), int(d['deg_j'])
            l = q & 0xffff
            assert q >> 16 == 0 and l in INV and s in INV, ('witness', c)
            subs_f = None
        else:
            continue
        Q = INV[s]
        gens = basis[c] + [e]
        subs = []
        for x in gens:
            y = actF(l, Q, x)
            sub = xor_subset(basis[j], y)
            if sub is None:
                nbad += 1
                print('IMAGE NOT IN SPAN: class %d gen %d -> %d not in span basis(%d)' % (c, x, y, j))
                sub = 0
            subs.append(sub)
        if subs_f is not None and subs[:len(basis[c])] != subs_f:
            nbad += 1
            print('SUBSETS DIFFER: class %d computed %s, witness file %s' % (c, subs[:len(basis[c])], subs_f))
        if not lb[c] <= lb[j]:
            nbad += 1
            print('BOUND SHORT: class %d lb %d > lb(%d) = %d' % (c, lb[c], j, lb[j]))
        ents.append('(%d, %d, %d, %d, %d, [%s])' % (c, e, l, s, j, ', '.join(str(x) for x in subs)))
    if mono and nmono != nmono_tab:
        nbad += 1
        print('MONOTONE COUNT: %d witnesses, %d monotone classes in the table' % (nmono, nmono_tab))
    assert nbad == 0, '%d problems' % nbad
    G = ['/-! # The degenerate and monotone rows of the class table (L5b; GENERATED by a script; do not',
         'edit).', '', 'Entry `(c, e, l, s, j, subs)`: class `c` has route 1; the extra vector `e` and the witness `(l, s)`, acting',
         'as `v ↦ l v s⁻¹` (`actF l (invN s) v`), map every generator of `basisOf c ++ [e]` into the span of `basisOf j`;',
         '`subs` lists, per generator, the subset of `basisOf j` whose XOR is the image. Degenerate rows (table route',
         '`deg`): Wang\'s witness. Monotone rows (table route `routeB` with no IP of its own, %d classes): `e = 0` and the' % nmono,
         'monotone witness, `j` a class of larger dimension. -/', '',
         'namespace B334.Tab2', '',
         'def degRows : List (Nat × Nat × Nat × Nat × Nat × List Nat) := [']
    G += ['  ' + x + (',' if i < len(ents) - 1 else '') for i, x in enumerate(ents)]
    G += [']', '', 'end B334.Tab2']
    open(os.path.join(out, 'DegData.lean'), 'w').write('\n'.join(G) + '\n')
    print('classes %d; deg rows %d (monotone %d); routes %s; lbOf nonzero %d; problems %d' % (
        N, len(ents), nmono, ' '.join('%d:%d' % (k, rlist.count(str(k))) for k in range(4)),
        sum(1 for c in lb if lb[c] > 0), nbad))


if __name__ == '__main__':
    main()
