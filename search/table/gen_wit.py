# gen_wit.py GLTAB OUT: the witness table of B334/Lem/OrbitTab.lean.
# For each 9-bit mask m (entry (i, j) at bit 3i+j, as E1x.toM3 and Statement.mat3) find P, Q in GL3(F2) (the bits of
# GLM in GLTAB = lean/B334/E1x/GLTab.lean of the release) with P*m*Q = canon[rkN(m)], canon = [0, 1, 10, 84], and write the Lean
# module OUT (a new file: refuses to overwrite) with WIT = sum of P << 9*(2m) and Q << 9*(2m+1).
# rkN and mulF are the definitions of B334/Lem/Orbit.lean and B334/E1x/Act.lean; both are cross-checked here against
# a plain matrix product and Gaussian elimination.  Orbit.lean re-checks every entry by decide +kernel.
import re
import sys


def mul(u, v):
    r = 0
    for i in range(3):
        for j in range(3):
            s = 0
            for k in range(3):
                s ^= ((u >> (3 * i + k)) & 1) & ((v >> (3 * k + j)) & 1)
            r |= s << (3 * i + j)
    return r


def mulF(u, v):
    return ((u & 73) * (v & 7)) ^ (((u >> 1) & 73) * ((v >> 3) & 7)) ^ (((u >> 2) & 73) * ((v >> 6) & 7))


def rkN(m):
    r0, r1, r2 = m & 7, (m >> 3) & 7, (m >> 6) & 7
    return ((0 if r0 == 0 else 1) + (0 if (r1 == 0 or r1 == r0) else 1)
            + (0 if (r2 == 0 or r2 == r0 or r2 == r1 or r2 == (r0 ^ r1)) else 1))


def rank_gauss(m):
    rows = [m & 7, (m >> 3) & 7, (m >> 6) & 7]
    rk = 0
    for bit in range(3):
        piv = None
        for idx in range(rk, 3):
            if (rows[idx] >> bit) & 1:
                piv = idx
                break
        if piv is None:
            continue
        rows[rk], rows[piv] = rows[piv], rows[rk]
        for idx in range(3):
            if idx != rk and (rows[idx] >> bit) & 1:
                rows[idx] ^= rows[rk]
        rk += 1
    return rk


def main():
    src = open(sys.argv[1]).read()
    GLM = int(re.search(r'def GLM : Nat := (0x[0-9a-f]+)', src).group(1), 16)
    gl = [P for P in range(512) if (GLM >> P) & 1]
    assert len(gl) == 168 and all(rank_gauss(P) == 3 for P in gl)
    assert all(mul(u, v) == mulF(u, v) for u in range(512) for v in range(512))
    canon = [0, 1, 10, 84]
    counts = [0, 0, 0, 0]
    W = 0
    for m in range(512):
        r = rkN(m)
        assert r == rank_gauss(m)
        counts[r] += 1
        t = canon[r]
        found = None
        for P in gl:
            Pm = mulF(P, m)
            for Q in gl:
                if mulF(Pm, Q) == t:
                    found = (P, Q)
                    break
            if found:
                break
        assert found is not None
        P, Q = found
        assert mul(mul(P, m), Q) == t
        W |= P << (9 * (2 * m))
        W |= Q << (9 * (2 * m + 1))
    assert counts == [1, 49, 294, 168]
    for m in range(512):
        P = (W >> (9 * (2 * m))) & 511
        Q = (W >> (9 * (2 * m + 1))) & 511
        assert (GLM >> P) & 1 and (GLM >> Q) & 1 and mulF(mulF(P, m), Q) == canon[rkN(m)]
    body = (
        "/-! # Witness table for the point orbits (generated by a script)\n\n"
        "For each 9-bit first factor `m` (entry `(i, j)` at bit `3i+j`), the 9-bit fields `2m` and `2m+1` of `WIT` "
        "hold\n`P` and `Q` in GL₃(F₂) (bits of `E1x.GLM`) with `P · m · Q = canonN (rkN m)`, where "
        "`canonN 0, 1, 2, 3 = 0, 1, 10, 84`.\n`B334/Lem/Orbit.lean` checks every entry by `decide +kernel` "
        "(`wit_all`). Ranks: %d mask of rank 0, %d of rank 1, %d of\nrank 2, %d of rank 3. -/\n\n"
        "namespace B334.Lem\n\n"
        "/-- fields `2m`, `2m+1` (9 bits each): the witnesses `P`, `Q` of mask `m` -/\n"
        "def WIT : Nat := %s\n\n"
        "end B334.Lem\n"
    ) % (counts[0], counts[1], counts[2], counts[3], hex(W))
    with open(sys.argv[2], 'x') as f:
        f.write(body)
    print("wrote", sys.argv[2], "bits", W.bit_length(), "counts", counts)


main()
