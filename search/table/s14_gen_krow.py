#!/usr/bin/env python3
"""s14_gen_krow.py ROW_JSON OUT_DIR [CHUNK] : the Lean modules of one method-K row.

From row<c>.json (written by emit_k.py or s16_flatcert.py) it writes, under OUT_DIR (= .../B334/MethodK/Rows):
  R<c>D.lean   data and the small facts K-pi, K-U, K-F1, K-M (M0 and N), K-L;
  R<c>W<k>.lean  one K-W chunk each (CHUNK masks, default 512; a chunk per module so they build in parallel);
  R<c>.lean    the chunk assembly (kwOK_of_chunks) and the row theorem `row : RowValid basis lb` (rowValid_of_K).
The generic lemmas are in B334/MethodK/{Subst,Flat,Quot,Cert}.lean.  This script only renders data; it checks nothing
(the kernel does).
"""
import hashlib
import json
import os
import sys

W = 32  # field width for packed masks


def pack(vals):
    v = 0
    for i, x in enumerate(vals):
        assert 0 <= x < (1 << W), x
        v |= x << (W * i)
    return v


def lst(xs):
    return '[' + ', '.join(str(x) for x in xs) + ']'


def main():
    src, out = sys.argv[1], sys.argv[2]
    C = int(sys.argv[3]) if len(sys.argv) > 3 else 512
    PFX = sys.argv[4] if len(sys.argv) > 4 else 'R'  # module-name prefix (mutants: e.g. MU1_)
    raw = open(src, 'rb').read()
    h = hashlib.sha256(raw).hexdigest()[:16]
    J = json.loads(raw)
    c, lb, na, p = J['class'], J['lb'], J['na'], J['p']
    f, nr = J['f'], J['nr']
    phi, side = J['phi'], J['side']
    Rp, Cp = J['Rp'], J['Cp']
    nR, nC = len(Rp), len(Cp)
    right = side == 'right'
    need = nC if right else nR
    assert need == J['need'], (need, J['need'])
    # chunks must cover exactly 0 … 2^need - 1 (kwAt is false-prone above the table), so C is a power of 2 <= 2^need
    assert C & (C - 1) == 0, 'CHUNK must be a power of 2'
    C = min(C, 1 << need)
    K = (1 << need) // C
    # mode order; Lean types use the products of T334's own types
    if p == 0:
        n0, m1, m2 = (str(na), '3 * 4', '4 * 3')
        n0v, m1v, m2v = na, 12, 12
        perm = None
    elif p == 1:
        n0, m1, m2 = ('3 * 4', '4 * 3', str(na))
        n0v, m1v, m2v = 12, 12, na
        perm = 'rankLE_perm1'
    elif p == 2:
        n0, m1, m2 = ('4 * 3', str(na), '3 * 4')
        n0v, m1v, m2v = 12, na, 12
        perm = 'rankLE_perm2'
    else:
        raise SystemExit('bad p')
    assert (J['n0'], J['m1'], J['m2']) == (n0v, m1v, m2v), (J['n0'], J['m1'], J['m2'], n0v, m1v, m2v)
    permfun = {0: '', 1: 'perm1 ', 2: 'perm2 '}[p]
    # flattening
    if phi == 'a':
        rowT, rowDim = 'Fin %d' % nr, str(nr)
        colT = 'Fin (%s) × Fin (%s)' % (m1, m2)
        colfun = '(⟨CpL.getD j.val 0 / (%s) %% (%s), Nat.mod_lt _ (by decide)⟩, ⟨CpL.getD j.val 0 %% (%s), Nat.mod_lt _ (by decide)⟩)' % (m2, m1, m2)
        flat, flatL, flatRank = 'flatA', 'flatAL', 'flatAL_rank'
    elif phi == 'b':
        rowT, rowDim = 'Fin (%s)' % m1, m1
        colT = 'Fin %d × Fin (%s)' % (nr, m2)
        colfun = '(⟨CpL.getD j.val 0 / (%s) %% %d, Nat.mod_lt _ (by decide)⟩, ⟨CpL.getD j.val 0 %% (%s), Nat.mod_lt _ (by decide)⟩)' % (m2, nr, m2)
        flat, flatL, flatRank = 'flatB', 'flatBL', 'flatBL_rank'
    elif phi == 'c':
        rowT, rowDim = 'Fin (%s)' % m2, m2
        colT = 'Fin %d × Fin (%s)' % (nr, m1)
        colfun = '(⟨CpL.getD j.val 0 / (%s) %% %d, Nat.mod_lt _ (by decide)⟩, ⟨CpL.getD j.val 0 %% (%s), Nat.mod_lt _ (by decide)⟩)' % (m1, nr, m1)
        flat, flatL, flatRank = 'flatC', 'flatCL', 'flatCL_rank'
    else:
        raise SystemExit('bad phi')
    # packed data
    U = J['U']
    Upk = pack([U[i][u] for i in range(n0v) for u in range(m1v)])
    M0pk = pack(J['M0'])
    # N: one small literal per matrix m (rows packed); an if-chain selects it (no big shifts in the inner loops)
    Nlits = [pack([J['N'][m][r] for r in range(nR)]) for m in range(nr * f)]
    Y = J['Y']
    assert len(Y) == (1 << need) - 1
    # Y: one literal per K-W chunk, indexed by z (entry 0 unused): Yz z shifts a small literal only (the kernel
    # evaluates call-by-name, so a big packed literal would be re-shifted at every use; leanK1 measured 12 GB)
    Yfull = [0] + list(Y)
    Ylits = [pack(Yfull[k * C:(k + 1) * C]) for k in range(K)]
    P = J['P']
    ns = 'B334.MethodK.%s%d' % (PFX, c)
    hdr = ['set_option maxRecDepth 1000000', 'set_option maxHeartbeats 0', '']
    os.makedirs(out, exist_ok=False) if not os.path.isdir(out) else None
    # ---- data module
    D = ['import B334.MethodK.Cert', ''] + hdr + [
        '/-! # Method K, row %d (class %d, lb %d): data and the small facts. GENERATED by a script' % (c, c, lb),
        'from its data; do not edit. Choice: %s. -/' % (J.get('choice', '-'),), '',
        'namespace %s' % ns, 'open B334.MethodK B334.Core', '',
        'def basis : List ℕ := %s' % lst(J['basis']),
        'def lb : ℕ := %d' % lb,
        'def piL : List ℕ := %s' % lst(J['pi']),
        'def π : Matrix (Fin %d) (Fin (3 * 3)) (ZMod 2) := Matrix.of fun x a => zbit (piL.getD x.val 0) a.val' % na,
        'def Upk : ℕ := 0x%x' % Upk,
        'def U : Fin (%s) → Fin (%s) → Fin (%s) → ZMod 2 := fun i u v =>' % (n0, m1, m2),
        '  zbit ((Upk >>> (32 * (i.val * (%s) + u.val))) %% 4294967296) v.val' % m1,
        'def FiL : List ℕ := %s' % lst(J['Fi']),
        'def Fi : Fin %d → Fin (%s) := fun l => ⟨FiL.getD l.val 0 %% (%s), Nat.mod_lt _ (by decide)⟩' % (f, n0, n0),
        'def RiL : List ℕ := %s' % lst(J['Ri']),
        'def Ri : Fin %d → Fin (%s) := fun s => ⟨RiL.getD s.val 0 %% (%s), Nat.mod_lt _ (by decide)⟩' % (nr, n0, n0),
        'def PuL : List ℕ := %s' % lst([q[0] for q in P]),
        'def PvL : List ℕ := %s' % lst([q[1] for q in P]),
        'def Pu : Fin %d → Fin (%s) := fun j => ⟨PuL.getD j.val 0 %% (%s), Nat.mod_lt _ (by decide)⟩' % (f, m1, m1),
        'def Pv : Fin %d → Fin (%s) := fun j => ⟨PvL.getD j.val 0 %% (%s), Nat.mod_lt _ (by decide)⟩' % (f, m2, m2),
        'def GmL : List ℕ := %s' % lst(J['G']),
        'def Gm : Matrix (Fin %d) (Fin %d) (ZMod 2) := mmat %d %d (fun i => GmL.getD i 0)' % (f, f, f, f),
        'def RpL : List ℕ := %s' % lst(Rp),
        'def CpL : List ℕ := %s' % lst(Cp),
        'def Rp : Fin %d → %s := fun r => ⟨RpL.getD r.val 0 %% (%s), Nat.mod_lt _ (by decide)⟩' % (nR, rowT, rowDim),
        'def Cp : Fin %d → %s := fun j => %s' % (nC, colT, colfun),
        'def M0pk : ℕ := 0x%x' % M0pk,
        'def M0r (r : ℕ) : ℕ := (M0pk >>> (32 * r)) % 4294967296',
    ] + ['def N%d : ℕ := 0x%x' % (m, Nlits[m]) for m in range(nr * f)] + [
        'def Nk (m : ℕ) : ℕ := ' + ' '.join('if m = %d then N%d else' % (m, m) for m in range(nr * f)) + ' 0',
        'def Nr (m r : ℕ) : ℕ := (Nk m >>> (32 * r)) % 4294967296',
    ] + ['def Y%d : ℕ := 0x%x' % (k, Ylits[k]) for k in range(K)] + [
        'def Yk (k : ℕ) : ℕ := ' + ' '.join('if k = %d then Y%d else' % (k, k) for k in range(K)) + ' 0',
        'def Yz (z : ℕ) : ℕ := (Yk (z / %d) >>> (32 * (z %% %d))) %% 4294967296' % (C, C), '',
        '/-- K-π -/',
        'theorem kpi : ∀ b ∈ basis, π.mulVec (vecOfMask (3 * 3) b) = 0 := by decide +kernel',
        '/-- K-U -/',
        'theorem kU : ∀ i u v, U i u v = %s(qproj π T334) i u v := by decide +kernel' % permfun,
        '/-- K-F1 -/',
        'theorem kF1 : Gm * Matrix.of (fun l j => U (Fi l) (Pu j) (Pv j)) = 1 := by decide +kernel',
        '/-- K-M, the constant part -/',
        'theorem kM0 : (%s (usub U Fi Ri 0)).submatrix Rp Cp = mmat %d %d M0r := by decide +kernel' % (flatL, nR, nC),
        '/-- K-M, the forced parts (`m = s·f + l`) -/',
        'theorem kN : ∀ (s : Fin %d) (l : Fin %d), (%s (eslice U Fi s l)).submatrix Rp Cp =' % (nr, f, flatL),
        '    mmat %d %d (Nr (s.val * %d + l.val)) := by decide +kernel' % (nR, nC, f),
        '/-- K-L -/',
        'theorem kL : lb ≤ %d + %d := by decide' % (f, need), '',
        'end %s' % ns]
    open(os.path.join(out, '%s%dD.lean' % (PFX, c)), 'w').write('\n'.join(D) + '\n')
    # ---- K-W chunks
    rb = 'true' if right else 'false'
    for k in range(K):
        Wm = ['import B334.MethodK.Rows.%s%dD' % (PFX, c), ''] + hdr + [
            '/-! # Method K, row %d: K-W chunk %d of %d (masks %d … %d). GENERATED; do not edit. -/' % (c, k, K, k * C, k * C + C - 1), '',
            'namespace %s' % ns, 'open B334.MethodK B334.Core', '',
            'theorem kW%d : B334.Core.allLT %d (fun i => kwAt M0r Nr (%d * %d) Yz %d %d %s (%d * %d + i)) = true := by' % (k, C, nr, f, nR, nC, rb, k, C),
            '  decide +kernel', '',
            'end %s' % ns]
        open(os.path.join(out, '%s%dW%d.lean' % (PFX, c, k)), 'w').write('\n'.join(Wm) + '\n')
    # ---- assembly
    cases = '\n'.join('    · exact B334.Core.allLT_spec kW%d i hi' % k for k in range(K))
    if perm is None:
        uproof = '      rw [hU]; exact hr'
    else:
        uproof = '      rw [hU]; exact %s _ r hr' % perm
    rank_ge = 'rank_ge_right' if right else 'rank_ge_left'
    hW = 'hW_right' if right else 'hW_left'
    A = ['\n'.join('import B334.MethodK.Rows.%s%dW%d' % (PFX, c, k) for k in range(K)), ''] + [
        '/-! # Method K, row %d: the row theorem. GENERATED by a script; do not edit. -/' % c, '',
        'namespace %s' % ns, 'open B334.MethodK B334.Core', '',
        'theorem kW : kwOK M0r Nr (%d * %d) Yz %d %d %d %s = true :=' % (nr, f, nR, nC, need, rb),
        '  kwOK_of_chunks %d %d (by decide) (fun k hk i hi => by' % (C, K),
        '    interval_cases k',
        cases + ')', '',
        'theorem hU : U = %s(qproj π T334) := funext fun i => funext fun u => funext fun v => kU i u v' % permfun, '',
        '/-- **Row %d**: R(T334 mod span basis) ≥ %d, by method K. -/' % (c, lb),
        'theorem row : RowValid basis lb :=',
        '  rowValid_of_K basis lb π (ker_of_basis π basis kpi) U',
        '    (fun r hr => by',
        uproof + ')',
        '    Fi Ri (linIndep_of_inv U Fi Pu Pv Gm kF1) %s %s' % (flatL, flatRank),
        '    (%s U Fi Ri %s Rp Cp (mmat %d %d M0r) (fun s l => mmat %d %d (Nr (s.val * %d + l.val))) kM0 kN' % (rank_ge, flatL, nR, nC, nR, nC, f),
        '      (%s kW)) kL' % hW, '',
        'end %s' % ns]
    open(os.path.join(out, '%s%d.lean' % (PFX, c)), 'w').write('\n'.join(A) + '\n')
    print('row %d: p=%d phi=%s side=%s need=%d nR=%d nC=%d f=%d nr=%d chunks=%d (C=%d) json sha %s' % (
        c, p, phi, side, need, nR, nC, f, nr, K, C, h))


if __name__ == '__main__':
    main()
