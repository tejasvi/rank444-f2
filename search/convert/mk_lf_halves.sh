#!/bin/bash
# mk_lf_halves.sh LEANDIR NS NLEAVES [HALF]: the leaf-check modules of run NS in modules of HALF leaves
# (default 50, so that each leaf module needs about 10 GB or less), under LEANDIR/B334/E1x/NS: Lh<p>.lean (`lh_<a>`, decide +kernel over
# HALF leaves) and Lf<q>.lean, which keeps the statement of the 100-leaf fact `lf_<a>` that Fin imports, proved by
# IPChk.allR_join of its two halves. Writes new files only (refuses if any exists).
LEAN=${1:?leandir}; NS=${2:?ns}; N=${3:?nleaves}; H=${4:-50}
D=$LEAN/B334/E1x/$NS
F='(fun k => leafB (LI.getD k (0, 0)))'
[ -d "$D" ] || { echo "no $D"; exit 2; }
for f in "$D"/Lh*.lean "$D"/Lf[0-9]*.lean; do [ -e "$f" ] && { echo "exists: $f"; exit 1; }; done
q=0
for a in $(seq 0 100 $((N - 1))); do
  m=$(( N - a < 100 ? N - a : 100 ))
  p1=$((2 * q)); m1=$(( m < H ? m : H ))
  printf '%s\n' "import B334.E1x.$NS.LfB" '' 'set_option maxHeartbeats 0' 'set_option maxRecDepth 100000' '' \
    "/-! # Leaves $a … $((a + m1 - 1)) of \`$NS\` (generated by a script; \`decide +kernel\`) -/" '' \
    "namespace B334.E1x.$NS" '' "theorem lh_$a : IPChk.allR $F $a $m1 = true := by" '  decide +kernel' '' \
    "end B334.E1x.$NS" > "$D/Lh$p1.lean"
  if [ "$m" -gt "$H" ]; then
    p2=$((2 * q + 1)); a2=$((a + H)); m2=$((m - H))
    printf '%s\n' "import B334.E1x.$NS.LfB" '' 'set_option maxHeartbeats 0' 'set_option maxRecDepth 100000' '' \
      "/-! # Leaves $a2 … $((a2 + m2 - 1)) of \`$NS\` (generated by a script; \`decide +kernel\`) -/" '' \
      "namespace B334.E1x.$NS" '' "theorem lh_$a2 : IPChk.allR $F $a2 $m2 = true := by" '  decide +kernel' '' \
      "end B334.E1x.$NS" > "$D/Lh$p2.lean"
    body="theorem lf_$a : IPChk.allR $F $a $m = true := IPChk.allR_join $F $a $H $m2 lh_$a lh_$a2"
    imps="import B334.E1x.$NS.Lh$p1
import B334.E1x.$NS.Lh$p2"
  else
    body="theorem lf_$a : IPChk.allR $F $a $m = true := lh_$a"
    imps="import B334.E1x.$NS.Lh$p1"
  fi
  printf '%s\n' "$imps" '' "/-! # Leaves $a … $((a + m - 1)) of \`$NS\`: the halves joined (generated by a script) -/" '' \
    "namespace B334.E1x.$NS" '' "$body" '' "end B334.E1x.$NS" > "$D/Lf$q.lean"
  q=$((q + 1))
done
echo "$NS: $q Lf modules, $(ls "$D"/Lh*.lean | wc -l) Lh modules"
